"""Step 7: Greedy Best-First Search.

Step 7A — Create Greedy Search
"""

def heuristic(stop_id, goal_id):
    lat1, lon1 = stop_coords[stop_id]
    lat2, lon2 = stop_coords[goal_id]

    return haversine(lat1, lon1, lat2, lon2)


def greedy_search(graph, start, goal):
    priority_queue = [(heuristic(start, goal), start, [start])]
    visited = set()
    nodes_expanded = 0

    while priority_queue:
        h, current, path = heapq.heappop(priority_queue)

        if current in visited:
            continue

        visited.add(current)
        nodes_expanded += 1

        if current == goal:
            return path, nodes_expanded

        for neighbor, distance in graph[current]:
            if neighbor not in visited:
                heapq.heappush(
                    priority_queue,
                    (
                        heuristic(neighbor, goal),
                        neighbor,
                        path + [neighbor]
                    )
                )

    return None, nodes_expanded

