def calculate_path_distance(path, graph):
    total_distance = 0

    for i in range(len(path) - 1):
        current = path[i]
        next_stop = path[i + 1]

        for neighbor, distance in graph[current]:
            if neighbor == next_stop:
                total_distance += distance
                break

    return total_distance

