"""Step 8A — Create the A* function"""

def astar(graph, start, goal):
    priority_queue = [
        (heuristic(start, goal), 0, start, [start])
    ]

    best_cost = {start: 0}
    nodes_expanded = 0

    while priority_queue:
        f, g, current, path = heapq.heappop(priority_queue)

        # Ignore outdated entries
        if g > best_cost[current]:
            continue

        nodes_expanded += 1

        # Goal found
        if current == goal:
            return path, g, nodes_expanded

        # Explore neighboring stops
        for neighbor, distance in graph[current]:

            new_g = g + distance

            if neighbor not in best_cost or new_g < best_cost[neighbor]:

                best_cost[neighbor] = new_g

                h = heuristic(neighbor, goal)
                new_f = new_g + h

                heapq.heappush(
                    priority_queue,
                    (
                        new_f,
                        new_g,
                        neighbor,
                        path + [neighbor]
                    )
                )

    return None, float("inf"), nodes_expanded

