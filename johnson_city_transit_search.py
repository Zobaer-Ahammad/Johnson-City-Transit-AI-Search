"""Step 5 — BFS
We will now implement the first algorithm from  proposal: Breadth-First Search (BFS). BFS ignores distance while searching and explores stops level by level

Step 5A — Create the BFS function
"""

from collections import deque

def bfs(graph, start, goal):
    queue = deque([(start, [start])])
    visited = {start}
    nodes_expanded = 0

    while queue:
        current, path = queue.popleft()
        nodes_expanded += 1

        # Goal found
        if current == goal:
            return path, nodes_expanded

        # Explore neighboring stops
        for neighbor, distance in graph[current]:
            if neighbor not in visited:
                visited.add(neighbor)
                queue.append((neighbor, path + [neighbor]))

    return None, nodes_expanded

